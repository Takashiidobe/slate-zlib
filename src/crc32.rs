/// If available, use the ARM processor CRC32 instruction.
/// Swap the bytes in a z_word_t to convert between little and big endian. Any
/// self-respecting compiler will optimize this to a single machine byte-swap
/// instruction, if one is available. This assumes that word_t is either 32 bits
/// or 64 bits.
fn byte_swap(word: c_ulong) -> c_ulong {
    (word & 18374686479671623680) >> 56i32
        | (word & 71776119061217280) >> 40i32
        | (word & 280375465082880) >> 24i32
        | (word & 1095216660480) >> 8i32
        | (word & 4278190080) << 8i32
        | (word & 16711680) << 24i32
        | (word & 65280) << 40i32
        | (word & 255) << 56i32
}

#[cfg(any(target_pointer_width = "32", windows))]
/// If available, use the ARM processor CRC32 instruction.
/// Swap the bytes in a z_word_t to convert between little and big endian. Any
/// self-respecting compiler will optimize this to a single machine byte-swap
/// instruction, if one is available. This assumes that word_t is either 32 bits
/// or 64 bits.
fn byte_swap(word: u32) -> u32 {
    (word & 4278190080) >> 24i32
        | (word & 16711680) >> 8i32
        | (word & 65280) << 8i32
        | (word & 255) << 24i32
}

