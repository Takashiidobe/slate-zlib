// Tables for byte-wise and braided CRC-32 calculations, and a table of powers
// of x for combining CRC-32s, all made by make_crc_table().
// CRC polynomial.
// p(x) reflected, with x^32 implied
/// Return a(x) multiplied by b(x) modulo p(x), where p(x) is the CRC polynomial,
/// reflected. For speed, this requires that a not be zero.
fn multmodp(a: c_ulong, mut b: c_ulong) -> c_ulong {
    let mut m: c_ulong = (2147483648 as c_ulong);
    let mut p: c_ulong = 0;
    loop {
        if a & m != 0 {
            p ^= b;
            if a & m.wrapping_sub(1) == 0 {
                break;
            }
        }
        m >>= 1i32;
        b = if b & 1 != 0 {
            b >> 1i32 ^ 3988292384
        } else {
            b >> 1i32
        };
    }
    p
}

#[cfg(unix)]
type __SlateHoist_x2nmodp = off_t;

#[cfg(windows)]
type __SlateHoist_x2nmodp = i64;

/// Return x^(n * 2^k) modulo p(x). Requires that x2n_table[] has been
/// initialized. n must not be negative.
fn x2nmodp(mut n: __SlateHoist_x2nmodp, mut k: u32) -> c_ulong {
    // x^0 == 1
    let mut p: c_ulong = (2147483648 as c_ulong);
    while n != 0 {
        if n & 1 != 0 {
            p = multmodp((unsafe { x2n_table.0[(k & 31) as usize] }) as c_ulong, p);
        }
        n >>= 1i32;
        k = k.wrapping_add(1);
    }
    p
}

